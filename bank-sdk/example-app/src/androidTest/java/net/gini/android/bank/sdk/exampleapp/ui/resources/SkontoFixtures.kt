package net.gini.android.bank.sdk.exampleapp.ui.resources

import java.time.LocalDate

/**
 * Fixture data for the Skonto screen and Return-Assistant-plus-Skonto tests.
 *
 * ## Why two of these are generated with a 2028 invoice date
 *
 * A skonto window is relative to the invoice date and only 7-14 days wide, so a real
 * invoice's discount stops being claimable about two weeks after it was issued.
 * `GetSkontoEdgeCaseUseCase` maps any `skontoDueDate` before today to
 * `SkontoEdgeCase.SkontoExpired`, and `GetSkontoDefaultSelectionStateUseCase` then arrives
 * with the discount switched off. A committed fixture can therefore only hold the
 * *claimable* state by printing an invoice date in the future — the same approach
 * [DueDateFixtures] takes for `paymentDueDate`.
 *
 * The expired states need no such trick, and use real invoices.
 *
 * | Asset | Invoice date | Skonto deadline | State under test |
 * |---|---|---|---|
 * | [VALID_ASSET] | 05.08.2028 | 19.08.2028 | claimable, no line items |
 * | [RA_VALID_ASSET] | 05.08.2028 | 19.08.2028 | skonto only — its position table does not extract |
 * | [PAST_ASSET] | 01.08.2025 | 08.08.2025 | expired, no line items |
 * | [RA_PAST_ASSET] | 15.08.2024 | 29.08.2024 | expired, two line items |
 * | [RA_VALID_2028_ASSET] | 15.08.2028 | 29.08.2028 | claimable, two line items **and** Skonto |
 *
 * [VALID_ASSET] and [RA_VALID_ASSET] are generated by
 * `src/androidTest/scripts/fixtures/gen_invoice_skonto_valid.py` and
 * `gen_invoice_skonto_ra_valid.py`. [PAST_ASSET] and [RA_PAST_ASSET] are real invoices
 * (a FreeFinance and an OTTO one) and are not regenerable — their printed dates are
 * already in the past, which is exactly what those cases need.
 *
 * REFRESH DEADLINE: regenerate [VALID_ASSET] and [RA_VALID_ASSET] with a later invoice
 * date (and update [VALID_SKONTO_DUE_DATE]) before mid-2028, when 19.08.2028 stops being
 * comfortably in the future. Re-validate the regenerated fixtures against the Gini API
 * before committing them — a different font produces different image bytes, and the
 * extraction is not guaranteed to survive that.
 *
 * ## Line items *and* a skonto discount
 *
 * The digital invoice screen only shows a skonto row when a single analysis result carries
 * `lineItems` **and** `skontoDiscounts`. Build `13a5f54e` measured both candidates on a real
 * device and each returned exactly one of the two:
 *
 * | Candidate | `lineItems` | `skontoDiscounts` |
 * |---|---|---|
 * | [RA_VALID_ASSET] (generated, prints a position table) | no | yes |
 * | [RA_PAST_ASSET] (OTTO invoice, prints skonto terms) | yes | no |
 *
 * So a printed position table is not necessarily extracted, and neither are printed skonto
 * terms — which is why a fixture has to be measured against the API rather than chosen by
 * reading it. That gap is what keeps [net.gini.android.bank.sdk.exampleapp.ui.testcases.DigitalInvoiceSkontoTests]
 * out of every BrowserStack script.
 *
 * Measured on 2026-11-25 (PP-3916): the API leaves out a Skonto whose deadline has passed.
 * [RA_PAST_ASSET] with only its invoice date moved to 2028 — [RA_VALID_2028_ASSET] — returns
 * both `lineItems` and `skontoDiscounts`. So the OTTO invoice's missing Skonto was its 2024
 * deadline, not the line items.
 */
object SkontoFixtures {

    /** A claimable discount and no line items: the standalone Skonto screen. */
    const val VALID_ASSET = "skonto_valid.jpeg"

    /**
     * Generated with a claimable discount and a printed position table — but the table is
     * **not** extracted as `lineItems`, so it lands on the standalone Skonto screen and is
     * unusable for the digital invoice case (build `13a5f54e`).
     */
    const val RA_VALID_ASSET = "skonto_ra_valid.jpeg"

    /** An expired discount and no line items: the standalone Skonto screen's edge case. */
    const val PAST_ASSET = "skonto_past.pdf"

    /**
     * The repository's Return-Assistant-plus-skonto invoice: an OTTO invoice printing a
     * position table *and* skonto terms.
     *
     * Only the line items extract — build `13a5f54e` reached the digital invoice screen
     * showing "1x Bettwäsche 2tg" with no skonto row, so `skontoDiscounts` came back empty.
     * It is still the closest fixture the repository has to TC-013, which is why
     * [net.gini.android.bank.sdk.exampleapp.ui.testcases.DigitalInvoiceSkontoTests] uses it,
     * and why that class is excluded from every run rather than deleted.
     */
    const val RA_PAST_ASSET = "Testrechnung-RA-Skonto.pdf"

    /**
     * Two line items **and** a claimable 3 % Skonto within 14 days: the Return Assistant with a
     * Skonto row, against the real API (`SkontoReturnAssistantTests`, PP-3916).
     *
     * It is [RA_PAST_ASSET] — the OTTO invoice, which extracts its line items — with the typed
     * invoice date moved from 15.08.2024 to 15.08.2028, so the Skonto deadline is 29.08.2028.
     * [RA_PAST_ASSET] extracted no `skontoDiscounts` while its deadline lay in the past; with a
     * future deadline the API returns both. Made by rendering the page (scan plus its typed
     * overlays), painting the date box white, typing the new date in Helvetica, and saving the
     * page as a JPEG PDF; nothing else on the page changed.
     *
     * REFRESH DEADLINE: move the date again before mid-2028. Re-measure against the API.
     */
    const val RA_VALID_2028_ASSET = "ra_skonto_valid_2028.pdf"

    /** "Rechnungsbetrag" printed on [RA_VALID_2028_ASSET]. */
    const val RA_VALID_2028_AMOUNT_TO_PAY = "105.20"

    /** The amount after Skonto printed on [RA_VALID_2028_ASSET]: 105,20 € − 3,16 € (the invoice prints 3,15 € and 102,04 €). */
    const val RA_VALID_2028_SKONTO_AMOUNT_TO_PAY = "102.04"

    /** The Skonto percentage printed on [RA_VALID_2028_ASSET]. */
    const val RA_VALID_2028_SKONTO_PERCENTAGE = "3"

    /** Must match the skonto deadline printed on [VALID_ASSET] and [RA_VALID_ASSET]. */
    val VALID_SKONTO_DUE_DATE: LocalDate = LocalDate.of(2028, 8, 19)

    /**
     * The full amount printed on [VALID_ASSET] and [RA_VALID_ASSET], as the extraction
     * reports it. Assertions stay on direction of change rather than exact figures wherever
     * the backend's own rounding could differ, but validation bounds need a number.
     */
    const val VALID_FULL_AMOUNT = "500.00"
}
